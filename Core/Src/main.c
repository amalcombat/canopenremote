/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_FDCAN1_Init();
  MX_TIM6_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */
  debug_step = 1;
       // Medium - ADC
  HAL_ADCEx_Calibration_Start(&hadc1, ADC_SINGLE_ENDED);
  debug_step = 2;




  CANopenNodeSTM32 canOpenNodeSTM32;
  canOpenNodeSTM32.CANHandle = &hfdcan1;
  canOpenNodeSTM32.HWInitFunction = MX_FDCAN1_Init;
  canOpenNodeSTM32.timerHandle = &htim6;
  canOpenNodeSTM32.desiredNodeID = 21;
  canOpenNodeSTM32.baudrate = 250;
  debug_step = 3;
  canopen_result = canopen_app_init(&canOpenNodeSTM32);
  debug_step = 4;

  // Disable DMA and ADC interrupts - just run in background


  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_values, 3);

  debug_step = 5;



  HAL_TIM_Base_Start(&htim2);




//  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_values, 2);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  debug_step = 10;

	    int16_t steering = ((int32_t)adc_values[0] - 2048) * 100 / 2048;
	    int16_t throttle = ((int32_t)adc_values[1] - 2048) * 100 / 2048;
	    int16_t pot_value  = ((int32_t)adc_values[2] - 2048) * 100 / 2048;

	    // Deadzone: ignore small values near center (joystick drift)
	    if (steering > -5 && steering < 5) steering = 0;
	    if (throttle > -5 && throttle < 5) throttle = 0;

	    // ========== READ SWITCHES (Active LOW - inverted) ==========
	     uint8_t main_arm   = !HAL_GPIO_ReadPin(MAIN_ARM_GPIO_Port, MAIN_ARM_Pin);
	     uint8_t fwd_bwd    = !HAL_GPIO_ReadPin(FWD_BWD_GPIO_Port, FWD_BWD_Pin);
	     uint8_t left_right = !HAL_GPIO_ReadPin(LFT_RGT_GPIO_Port, LFT_RGT_Pin);
	     uint8_t cw_acw     = !HAL_GPIO_ReadPin(CW_ACW_GPIO_Port, CW_ACW_Pin);
	     uint8_t crab       = !HAL_GPIO_ReadPin(CRAB_GPIO_Port, CRAB_Pin);
	     uint8_t steer      = !HAL_GPIO_ReadPin(STEER_GPIO_Port, STEER_Pin);
	     uint8_t drive_arm  = !HAL_GPIO_ReadPin(drv_arm_GPIO_Port, drv_arm_Pin);
	     uint8_t emergency  = !HAL_GPIO_ReadPin(emergency_GPIO_Port, emergency_Pin);

	     debug_main_arm = main_arm;
	     debug_fwd_bwd = fwd_bwd;
	     debug_left_right = left_right;
	     debug_cw_acw = cw_acw;
	     debug_crab = crab;
	     debug_steering = steer;
	     debug_drive_arm = drive_arm;
	     debug_emergency = emergency;

	    OD_RAM.x2000_joystick_highestSubIndex.joystick_X = steering;
	    OD_RAM.x2000_joystick_highestSubIndex.joystick_Y = throttle;

	    // Switches (0x2001)
	        OD_RAM.x2001_switches.main_arm   = main_arm;
	        OD_RAM.x2001_switches.fwd_bwd    = fwd_bwd;
	        OD_RAM.x2001_switches.left_right = left_right;
	        OD_RAM.x2001_switches.cw_acw     = cw_acw;
	        OD_RAM.x2001_switches.crab       = crab;
	        OD_RAM.x2001_switches.steering   = steer;
	        OD_RAM.x2001_switches.drive_arm  = drive_arm;
	        OD_RAM.x2001_switches.emergency  = emergency;

	        // Potentiometer (0x2002)
	        OD_RAM.x2002_potentiometer.pot_value = pot_value;

	        // ========== READ PLC COMMANDS VIA RPDO1 (OD 0x2003) ==========
	        // The CANopen stack writes incoming RPDO data to OD_RAM.x2003_plc_commands
	        // These values are updated automatically when the PLC sends to CAN ID 0x215
	        //
	        // NOTE: You must regenerate OD.h/OD.c from the updated XDD file
	        //       using CANopenEditor before this code will compile.
	        plc_command = OD_RAM.x2003_plc_commands.command;
	        plc_value1  = OD_RAM.x2003_plc_commands.value1;
	        plc_value2  = OD_RAM.x2003_plc_commands.value2;
	        plc_flags   = OD_RAM.x2003_plc_commands.flags;

	        // ========== ACT ON PLC COMMANDS ==========
	        // Add your command handling logic here. Example:
	        // if (plc_command == 1) { /* do something with plc_value1, plc_value2 */ }
	        // if (plc_flags & 0x01) { /* flag bit 0 is set */ }

	        // ========== PROCESS CANOPEN ==========
	        canopen_app_process();

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

